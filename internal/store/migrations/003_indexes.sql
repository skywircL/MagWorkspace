CREATE TABLE IF NOT EXISTS index_cleanup (
 id varchar(32) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 profile_id varchar(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 generation varchar(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 not_before datetime(6) NOT NULL,
 created_at datetime(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 UNIQUE KEY index_cleanup_generation(profile_id,generation),
 KEY index_cleanup_due(not_before,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE IF NOT EXISTS document_indexes (
 id varchar(32) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 workspace_id varchar(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 document_id varchar(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 version_id varchar(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 profile_id varchar(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 embedding_model varchar(255) NOT NULL,
 dimensions int NOT NULL,
 source_sha256 char(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 status varchar(16) NOT NULL DEFAULT 'queued',
 error_code varchar(100) NOT NULL DEFAULT '',
 attempts int NOT NULL DEFAULT 0,
 generation varchar(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT '',
 lease_expires_at datetime(6) NULL,
 artifact_key varchar(512) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT '',
 artifact_sha256 varchar(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT '',
 chunk_count int NOT NULL DEFAULT 0,
 created_by varchar(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 created_at datetime(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 updated_at datetime(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 finished_at datetime(6) NULL,
 UNIQUE KEY document_indexes_version_profile(version_id,profile_id),
 KEY document_indexes_claim(profile_id,status,lease_expires_at,created_at),
 KEY document_indexes_generation(profile_id,generation),
 CONSTRAINT document_indexes_workspace_fk FOREIGN KEY(workspace_id) REFERENCES workspaces(id) ON DELETE CASCADE,
 CONSTRAINT document_indexes_document_fk FOREIGN KEY(document_id) REFERENCES documents(id) ON DELETE CASCADE,
 CONSTRAINT document_indexes_version_fk FOREIGN KEY(version_id) REFERENCES document_versions(id) ON DELETE CASCADE,
 CONSTRAINT document_indexes_creator_fk FOREIGN KEY(created_by) REFERENCES users(id),
 CONSTRAINT document_indexes_status CHECK(status IN ('queued','running','ready','failed')),
 CONSTRAINT document_indexes_attempts CHECK(attempts >= 0),
 CONSTRAINT document_indexes_dimensions CHECK(dimensions > 0),
 CONSTRAINT document_indexes_manifest CHECK(chunk_count BETWEEN 0 AND 2048 AND (status<>'ready' OR (chunk_count>0 AND OCTET_LENGTH(artifact_key)>0 AND OCTET_LENGTH(artifact_sha256)=64)))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
